import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
const remote=new URL('../signal-state.mjs',import.meta.url);
const {validateSnapshot,signalPresentation,allocationText}=await import(existsSync(remote)?remote:new URL('../pwa/docs/signal-state.mjs',import.meta.url));
const path=process.env.PWA_BLEND_SNAPSHOT_TEST_OUTPUT;
assert.ok(path,'Require deterministic four-sleeve fixtures from Python tests');
const [thursday,friday]=JSON.parse(readFileSync(path,'utf8'));
validateSnapshot(thursday);validateSnapshot(friday);
assert.equal(thursday.schemaVersion,3);
assert.equal(signalPresentation(thursday,new Date('2026-10-30T06:45:00Z')).state,'今日尾盘待执行');
assert.match(signalPresentation(thursday).description,/四份(?:方案|均维持)/);
const pendingTrade=structuredClone(thursday);pendingTrade.latestSignal.traded=true;
assert.match(signalPresentation(pendingTrade).description,/四份方案/);
assert.match(signalPresentation(friday).description,/确认配置/);
assert.match(allocationText(friday.confirmedWeights),/创业板.*纳指.*现金/);
const clone=()=>structuredClone(friday);
let bad=clone();bad.confirmedWeights.CASH+=.1;assert.throws(()=>validateSnapshot(bad),/合计配置/);
bad=clone();bad.latestSignal.plannedWeights.CASH+=.1;assert.throws(()=>validateSnapshot(bad),/目标配置/);
bad=clone();bad.latestSignal.sleeves[0].phase=bad.latestSignal.sleeves[1].phase;assert.throws(()=>validateSnapshot(bad),/四份方案/);
bad=clone();bad.rules.sizeGateEnabled=true;assert.throws(()=>validateSnapshot(bad),/规则或审计/);
bad=clone();bad.candidates.find(c=>c.eligible).riskScore=null;assert.throws(()=>validateSnapshot(bad),/风险分数/);
bad=clone();bad.latestSignal.sleeves[0].plannedWeight-=.01;assert.throws(()=>validateSnapshot(bad),/子方案/);
const mixed=clone();mixed.holding='MIXED';mixed.exposure=.8;mixed.confirmedWeights={sz159915:.3,sh513100:.5,CASH:.2};
const confirmation=mixed.decisions.find(d=>d.executionDate===mixed.positionAsOf);
confirmation.actualHolding='MIXED';confirmation.executionWeight=.8;confirmation.executionWeights=mixed.confirmedWeights;
mixed.latestSignal.executionWeights=mixed.confirmedWeights;mixed.latestSignal.executionWeight=.8;mixed.latestSignal.actualHolding='MIXED';
validateSnapshot(mixed);
const skipped=structuredClone(thursday);skipped.latestSignal={...skipped.latestSignal,status:'skipped_holiday',target:null,plannedWeight:null,traded:false,skipReason:'friday_closed'};
skipped.latestSignal.sleeves=skipped.latestSignal.sleeves.map(s=>({...s,status:'skipped_holiday',target:null,plannedWeight:null,traded:false}));
validateSnapshot(skipped);assert.match(signalPresentation(skipped).description,/跳过执行/);
console.log('PASS: four-sleeve pending/confirmed/mixed/holiday presentation, allocation integrity and risk-score validation.');
